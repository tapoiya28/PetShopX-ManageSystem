    )

    UPDATE SANPHAM
    SET LOAI = N'Thuốc'
    WHERE EXISTS (
        SELECT 1 
        FROM THUOC TH
        WHERE TH.MATHUOC = SANPHAM.MASP
    )

    UPDATE SANPHAM
    SET LOAI = N'Gói tiêm'
    WHERE EXISTS (
        SELECT 1 
        FROM GoiTiem GT
        WHERE GT.MAGOITIEM  = SANPHAM.MASP
    )

    UPDATE NHANVIEN
    SET VAITRO = 'NV'
    UPDATE NHANVIEN
