UPDATE HOADON
SET TONGTIEN = ISNULL((
    SELECT SUM(SOLUONG * GIABAN)
    FROM CHITIETHOADON ct
    WHERE HOADON.MAHD = ct.MAHD
), 0)


UPDATE HOADON
SET KHUYENMAI = 0
WHERE KHUYENMAI IS NULL

    UPDATE HOADON
    SET TongTien = 
        ISNULL(
            (SELECT SUM(CTHD.SOLUONG * CTHD.GIABAN)
                FROM ChiTietHoaDon CTHD
                WHERE CTHD.MAHD = HOADON.MAHD), 0)
    UPDATE CHITIEU
    SET CHITIEU = 
        ISNULL(
            (
                SELECT SUM(HD.TONGTIEN * HD.KHUYENMAI / 100.0)
                FROM HOADON HD
                WHERE YEAR(HD.NGAYLAP) = CHITIEU.NAM
                ), 0    
            )


UPDATE NHANVIEN
