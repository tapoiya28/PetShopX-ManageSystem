UPDATE CAPBAC
SET MUCCHITIEU = 0,
    MUCGIUHANG = 0
WHERE TENCAPBAC = N'Cơ bản'

UPDATE CAPBAC
SET MUCCHITIEU = 5000000,
    MUCGIUHANG = 3000000
WHERE TENCAPBAC = N'Thân thiết'

UPDATE CAPBAC
SET MUCCHITIEU = 12000000,
    MUCGIUHANG = 8000000
WHERE TENCAPBAC = N'VIP'

UPDATE KHACHHANG
SET DIEMTICHLUY = 0

UPDATE KHACHHANG
SET DIEMTICHLUY = ISNULL(
    (SELECT SUM(TONGTIEN * KHUYENMAI / 100.0) / 10000
    FROM HOADON HD
    WHERE HD.MAKH = KHACHHANG.MAKH)
    , 0)

UPDATE KHACHHANG 
SET TENCAPBAC = N'Cơ bản'
WHERE (SELECT SUM(CHITIEU) FROM CHITIEU WHERE CHITIEU.MAKH = KHACHHANG.MAKH GROUP BY Nam) < 5000000

UPDATE KHACHHANG 
SET TENCAPBAC = N'Thân thiết'
WHERE (SELECT SUM(CHITIEU) FROM CHITIEU WHERE CHITIEU.MAKH = KHACHHANG.MAKH GROUP BY Nam) >= 5000000
AND (SELECT SUM(CHITIEU) FROM CHITIEU WHERE CHITIEU.MAKH = KHACHHANG.MAKH GROUP BY Nam) < 12000000

UPDATE KHACHHANG 
SET TENCAPBAC = N'VIP'
WHERE (SELECT SUM(CHITIEU) FROM CHITIEU WHERE CHITIEU.MAKH = KHACHHANG.MAKH GROUP BY Nam) >= 12000000
