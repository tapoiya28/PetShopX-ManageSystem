--- 4. KINH DOANH
CREATE TABLE HOADON (
    MAHD        INTEGER IDENTITY(1,1) PRIMARY KEY,
    NGAYLAP     DATETIME CHECK (NGAYLAP <= GETDATE()),
    KHUYENMAI   INTEGER CHECK (KHUYENMAI >= 0 AND KHUYENMAI <= 100) DEFAULT 0,
    TONGTIEN    DECIMAL(12, 2) CHECK (TONGTIEN > 0),
    MACN        INTEGER NOT NULL,
    MAKH        INTEGER NOT NULL,
    MANV        INTEGER NOT NULL,
    TRANGTHAI   NVARCHAR(20) NOT NULL DEFAULT N'Chưa thanh toán' CHECK (TRANGTHAI IN (N'Chưa thanh toán', N'Đã thanh toán', N'Đã hủy'))
)

CREATE TABLE SANPHAM (
    MASP    INTEGER IDENTITY(1,1) PRIMARY KEY,
    TENSP   NVARCHAR(50) NOT NULL,
    DONGIA  INTEGER NOT NULL CHECK (DONGIA > 0),
    TONKHO  INTEGER NOT NULL CHECK (TONKHO >= 0),
    LOAI    NVARCHAR(10) NOT NULL CHECK (LOAI IN (N'Sản phẩm', N'Thuốc', N'Vacxin', N'Gói tiêm', N'Dịch vụ'))
)

CREATE TABLE CHITIETHOADON(
    MAHD    INTEGER,
    MASP    INTEGER,
    SOLUONG INTEGER NOT NULL CHECK (SOLUONG > 0),
    GIABAN  INTEGER NOT NULL CHECK (GIABAN > 0),
    CONSTRAINT PK_CHITIETHOADON PRIMARY KEY (MAHD, MASP)
)

-- Bảng con của SANPHAM, dùng lại MASP làm PK
CREATE TABLE DICHVU (
    MADV INTEGER PRIMARY KEY,
