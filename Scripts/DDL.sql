--- KINH DOANH
CREATE TABLE HOADON (
    MAHD CHAR(5) PRIMARY KEY,
    NGAYLAP DATETIME CHECK (NGAYLAP <= GETDATE()),
    KHUYENMAI INTEGER CHECK (KHUYENMAI >= 0),
    TONGTIEN DECIMAL(12, 2) CHECK (TONGTIEN > 0),
    DIEM INTEGER,
    MACN CHAR(5) NOT NULL,
    MAKH CHAR(10) NOT NULL,
    MANV CHAR(5) NOT NULL
)

CREATE TABLE HOADON_partitioned (
    MAHD CHAR(5) NOT NULL,
    NGAYLAP DATETIME CHECK (NGAYLAP <= GETDATE()),
    KHUYENMAI INTEGER CHECK (KHUYENMAI >= 0),
    TONGTIEN DECIMAL(12, 2) CHECK (TONGTIEN > 0),
    DIEM INTEGER,
    MACN CHAR(5) NOT NULL,
    MAKH CHAR(10) NOT NULL,
    MANV CHAR(5) NOT NULL
    CONSTRAINT PK_HOADON_partitioned PRIMARY KEY CLUSTERED (NGAYLAP, MAHD) ON ps_HoaDonByNgayLap(NGAYLAP)
)

