--- KHACH HANG VA THU CUNG
CREATE TABLE CAPBAC (
    TENCAPBAC   NVARCHAR(15) PRIMARY KEY CHECK (TENCAPBAC IN (N'Cơ bản', N'Thân thiết', N'VIP')),
    MUCCHITIEU  INTEGER NOT NULL CHECK (MUCCHITIEU >= 0),
    MUCGIUHANG  INTEGER NOT NULL CHECK (MUCGIUHANG >= 0)
)


CREATE TABLE KHACHHANG (
    MAKH        INTEGER IDENTITY(1,1) PRIMARY KEY,
    TENKH       NVARCHAR(50) NOT NULL,  
    SDT         CHAR(10) NOT NULL, 
    DIACHI      NVARCHAR(100),
    TENCAPBAC   NVARCHAR(15) DEFAULT N'Cơ bản',
    DIEMTICHLUY  INTEGER NOT NULL CHECK (DIEMTICHLUY >= 0),
    -- SDT phải là duy nhất
    CONSTRAINT UQ_KHACHHANG_SDT UNIQUE (SDT)
)

CREATE TABLE THUCUNG (
    MATC        INTEGER IDENTITY(1,1) PRIMARY KEY,
    TENTC       NVARCHAR(50) NOT NULL,   
    LOAI        NVARCHAR(20) NOT NULL,
    TUOI        TINYINT,
    GIOITINH    NVARCHAR(5) NOT NULL CHECK (GIOITINH IN (N'Đực', N'Cái')),
    TINHTRANG   NVARCHAR(20) NOT NULL CHECK (TINHTRANG IN (N'Bình thường', N'Đang điều trị')) DEFAULT N'Bình thường',
    MAKH        INTEGER NOT NULL
)

CREATE TABLE LICHHEN (
    MALICHHEN   INTEGER IDENTITY(1,1) PRIMARY KEY,
    NGAYHEN     DATE NOT NULL,
    THOIGIAN    TIME NOT NULL,
    NOIDUNG     NVARCHAR(200),
    MAKH        INTEGER NOT NULL,
    MACN        INTEGER NOT NULL,    
    MALOAIDV    INTEGER NOT NULL,    
    CONSTRAINT UQ_LICHEN_NGAYHEN_THOIGIAN_MACN_MAKH
        UNIQUE (NGAYHEN, THOIGIAN, MACN, MAKH)
)

CREATE TABLE CHITIEU (
    MAKH         INTEGER NOT NULL,
    NAM          SMALLINT NOT NULL,
    CHITIEU      DECIMAL(12,2) NOT NULL CHECK (CHITIEU >= 0),
    CONSTRAINT PK_CHITIEU PRIMARY KEY (MAKH, NAM)
)

CREATE TABLE DANHGIA (
    MADANHGIA       INTEGER IDENTITY(1,1) PRIMARY KEY,
    DIEMDICHVU      TINYINT CHECK (DIEMDICHVU BETWEEN 1 AND 5),
    MUCDOHAILONG    TINYINT CHECK (MUCDOHAILONG BETWEEN 1 AND 5),
    BINHLUAN        NVARCHAR(100) NULL,
    MAKH            INTEGER NOT NULL,
    MAHD            INTEGER NOT NULL,
    -- Một hóa đơn chỉ được đánh giá một lần
    CONSTRAINT UQ_DANHGIA_MAHD UNIQUE (MAHD)
)

