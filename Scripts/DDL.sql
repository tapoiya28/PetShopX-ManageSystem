    MUCLENHANG  DECIMAL(12, 2) NOT NULL CHECK (MUCLENHANG >= 0),
    MUCGIUHANG  DECIMAL(11, 2) NOT NULL CHECK (MUCGIUHANG >= 0)
)

CREATE TABLE KHACHHANG (
    MAKH        INT IDENTITY(1,1) PRIMARY KEY, -- Đổi sang INT tự tăng
    TENKH       NVARCHAR(50) NOT NULL,  
    SDT         CHAR(10) NOT NULL, 
    DIACHI      NVARCHAR(100),
    TENCAPBAC   NVARCHAR(15) DEFAULT N'Đồng',
    CONSTRAINT UQ_KHACHHANG_SDT UNIQUE (SDT)
)

CREATE TABLE THUCUNG (
    MATC        INT IDENTITY(1,1) PRIMARY KEY, -- Đổi sang INT tự tăng
    LOAI        NVARCHAR(20) NOT NULL,
    GIONG       NVARCHAR(50),
    TUOI        TINYINT,
    GIOITINH    NVARCHAR(5) NOT NULL CHECK (GIOITINH IN (N'Đực', N'Cái')),
    TINHTRANG   NVARCHAR(20) NOT NULL CHECK (TINHTRANG IN (N'Bình thường', N'Đang điều trị')),
    MAKH        INT NOT NULL -- FK kiểu INT
)

CREATE TABLE LICHHEN (
    MALICHHEN   INT IDENTITY(1,1) PRIMARY KEY, -- Đổi sang INT tự tăng
    NGAYHEN     DATE NOT NULL,
    THOIGIAN    TIME NOT NULL,
    NOIDUNG     NVARCHAR(200) NULL,
    MAKH        INT NOT NULL,
    MACN        INT NOT NULL,    
    MALOAIDV    INT NOT NULL,    
    CONSTRAINT UQ_LICHEN_NGAYHEN_THOIGIAN_MACN_MAKH UNIQUE (NGAYHEN, THOIGIAN, MACN, MAKH)
)

CREATE TABLE LICHHEN_partitioned (
    MALICHHEN   INT, -- Partitioned table thường không dùng Identity nếu copy dữ liệu từ bảng chính, hoặc dùng Identity nếu insert trực tiếp. Ở đây để INT thường cho an toàn logic partition.
    NGAYHEN     DATE NOT NULL,
    THOIGIAN    TIME NOT NULL,
    NOIDUNG     NVARCHAR(200) NULL,
    MAKH        INT NOT NULL,
    MACN        INT NOT NULL,    
    MALOAIDV    INT NOT NULL,
    CONSTRAINT PK_LICHEN_partitioned PRIMARY KEY CLUSTERED (NGAYHEN, MALICHHEN) ON ps_LichHenByNgayHen(NGAYHEN),
    CONSTRAINT UQ_LICHEN_partitioned_NgayHen_ThoiGian_MaCN_MaKH UNIQUE (NGAYHEN, THOIGIAN, MACN, MAKH) ON ps_LichHenByNgayHen(NGAYHEN)
)

CREATE TABLE CHITIEU (
    MAKH        INT NOT NULL,
    NAM         SMALLINT NOT NULL,
