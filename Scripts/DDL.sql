    THOIGIANTHUCHIEN INTEGER CHECK (THOIGIANTHUCHIEN > 0)
)

CREATE TABLE THUOC (
    MATHUOC INTEGER PRIMARY KEY,
    DONVI   NVARCHAR(5) NOT NULL CHECK (DONVI IN (N'Viên', N'Chai', N'Tuýp', N'Hộp', N'Vỉ')),
    NGAYSX  DATE NOT NULL CHECK (NGAYSX <= GETDATE()),
    HSD     INTEGER NOT NULL CHECK (HSD > 0) 
)

CREATE TABLE VACXIN (
    MAVACXIN        INTEGER PRIMARY KEY,
    NGAYSX          DATE NOT NULL CHECK (NGAYSX <= GETDATE()),
    HSD             INTEGER NOT NULL CHECK (HSD > 0), -- n tháng kể từ ngày sản xuất
    DOTUOIAPDUNG    INTEGER NOT NULL CHECK (DOTUOIAPDUNG > 0) -- tháng
)

CREATE TABLE GOITIEM (
    MAGOITIEM   INTEGER PRIMARY KEY,
    THOIGIAN    INTEGER NOT NULL CHECK (THOIGIAN >= 0),
    KHUYENMAI   INTEGER CHECK (KHUYENMAI >= 0) DEFAULT 5
)

CREATE TABLE CHITIETGOITIEM (
    MAGOITIEM   INTEGER,
    MAVACXIN    INTEGER,
    SOLUONG     INTEGER CHECK (SOLUONG > 0),
    CONSTRAINT PK_CHITIETGOITIEM PRIMARY KEY (MAGOITIEM, MAVACXIN)
)

CREATE TABLE DANGKYGOITIEM (
    MAGOITIEM   INTEGER,
    MATC        INTEGER,
